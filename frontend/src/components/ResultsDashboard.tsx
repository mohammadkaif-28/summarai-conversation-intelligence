import {
  CheckSquare,
  Download,
  FileText,
  Gavel,
  Plus,
  Save,
  Sparkles,
  Tags,
  Trash2,
} from "lucide-react";
import type { ReactNode } from "react";
import { Button } from "@/components/ui/button";
import {
  AlertDialog,
  AlertDialogAction,
  AlertDialogCancel,
  AlertDialogContent,
  AlertDialogDescription,
  AlertDialogFooter,
  AlertDialogHeader,
  AlertDialogTitle,
  AlertDialogTrigger,
} from "@/components/ui/alert-dialog";
import {
  DropdownMenu,
  DropdownMenuContent,
  DropdownMenuItem,
  DropdownMenuTrigger,
} from "@/components/ui/dropdown-menu";
import { CopyButton } from "@/components/CopyButton";
import { actionItemsToText, downloadReport } from "@/lib/report";
import type { AnalysisResponse } from "@/types/analysis";

interface ResultsDashboardProps {
  result: AnalysisResponse;
  onNewAnalysis: () => void;
  onSave?: () => void;
  saved?: boolean;
  onDelete?: () => void;
  subtitle?: string;
}

function InsightCard({
  title,
  icon,
  copyValue,
  children,
}: {
  title: string;
  icon: ReactNode;
  copyValue: string;
  children: ReactNode;
}) {
  return (
    <section className="premium-border flex flex-col rounded-2xl bg-card/90 p-6 shadow-card backdrop-blur-xl transition-all duration-300 hover:-translate-y-0.5 hover:shadow-glow">
      <header className="mb-4 flex items-center justify-between gap-2">
        <h3 className="flex items-center gap-2 text-sm font-semibold tracking-wide uppercase">
          <span className="text-primary" aria-hidden>
            {icon}
          </span>
          {title}
        </h3>
        {copyValue ? <CopyButton value={copyValue} /> : null}
      </header>
      <div className="flex-1 text-sm">{children}</div>
    </section>
  );
}

function EmptyNote({ children }: { children: ReactNode }) {
  return <p className="text-sm text-muted-foreground">{children}</p>;
}

export function ResultsDashboard({
  result,
  onNewAnalysis,
  onSave,
  saved,
  onDelete,
  subtitle,
}: ResultsDashboardProps) {
  const { summary, insights } = result;

  return (
    <div className="space-y-6 animate-in fade-in duration-300">
      <div className="flex flex-wrap items-start justify-between gap-3">
        <div>
          <p className="mb-1 text-xs font-semibold uppercase text-primary">Generated by SummarAI</p>
          <h2 className="text-2xl font-semibold tracking-tight">Analysis Results</h2>
          {subtitle ? <p className="text-sm text-muted-foreground">{subtitle}</p> : null}
        </div>
        <div className="flex flex-wrap items-center gap-2">
          {onSave ? (
            <Button variant="outline" size="sm" onClick={onSave} disabled={saved}>
              <Save className="size-4" aria-hidden />
              {saved ? "Saved" : "Save to History"}
            </Button>
          ) : null}
          <DropdownMenu>
            <DropdownMenuTrigger asChild>
              <Button variant="outline" size="sm">
                <Download className="size-4" aria-hidden />
                Download Report
              </Button>
            </DropdownMenuTrigger>
            <DropdownMenuContent align="end">
              <DropdownMenuItem onSelect={() => downloadReport(result, "txt")}>
                Plain text (.txt)
              </DropdownMenuItem>
              <DropdownMenuItem onSelect={() => downloadReport(result, "md")}>
                Markdown (.md)
              </DropdownMenuItem>
            </DropdownMenuContent>
          </DropdownMenu>
          {onDelete ? (
            <AlertDialog>
              <AlertDialogTrigger asChild>
                <Button variant="outline" size="sm">
                  <Trash2 className="size-4" aria-hidden />
                  Delete
                </Button>
              </AlertDialogTrigger>
              <AlertDialogContent>
                <AlertDialogHeader>
                  <AlertDialogTitle>Delete this saved analysis?</AlertDialogTitle>
                  <AlertDialogDescription>
                    This removes the analysis from your local history. It cannot be undone.
                  </AlertDialogDescription>
                </AlertDialogHeader>
                <AlertDialogFooter>
                  <AlertDialogCancel>Cancel</AlertDialogCancel>
                  <AlertDialogAction onClick={onDelete}>Delete</AlertDialogAction>
                </AlertDialogFooter>
              </AlertDialogContent>
            </AlertDialog>
          ) : null}
          <Button size="sm" onClick={onNewAnalysis}>
            <Plus className="size-4" aria-hidden />
            New Analysis
          </Button>
        </div>
      </div>

      <section className="premium-border rounded-2xl bg-card/90 p-7 shadow-card backdrop-blur-xl sm:p-9">
        <header className="mb-4 flex items-center justify-between gap-2">
          <h3 className="flex items-center gap-2 text-lg font-semibold">
            <Sparkles className="size-5 text-primary" aria-hidden />
            AI Summary
          </h3>
          <div className="flex items-center gap-1">
            <CopyButton value={summary} />
            <Button
              variant="ghost"
              size="sm"
              className="h-8 gap-1.5 px-2 text-xs text-muted-foreground hover:text-foreground"
              onClick={() => downloadReport(result, "txt")}
            >
              <Download className="size-3.5" aria-hidden />
              Download
            </Button>
          </div>
        </header>
        {summary ? (
          <p className="text-base leading-8 whitespace-pre-line text-card-foreground/90">{summary}</p>
        ) : (
          <EmptyNote>No summary was returned for this conversation.</EmptyNote>
        )}
      </section>

      <div className="grid gap-5 lg:grid-cols-2">
        <InsightCard
          title="Key Points"
          icon={<FileText className="size-4" />}
          copyValue={insights.key_points.join("\n")}
        >
          {insights.key_points.length ? (
            <ul className="space-y-2.5">
              {insights.key_points.map((point, i) => (
                <li
                  key={`${i}-${point.slice(0, 12)}`}
                  className="flex gap-3 rounded-xl bg-muted/50 px-3 py-2.5 leading-relaxed"
                >
                  <span className="mt-2 size-1.5 shrink-0 rounded-full bg-primary" aria-hidden />
                  <span>{point}</span>
                </li>
              ))}
            </ul>
          ) : (
            <EmptyNote>No key points were identified.</EmptyNote>
          )}
        </InsightCard>

        <InsightCard
          title="Action Items"
          icon={<CheckSquare className="size-4" />}
          copyValue={actionItemsToText(result)}
        >
          {insights.action_items.length ? (
            <ul className="space-y-2.5">
              {insights.action_items.map((item, i) => (
                <li
                  key={`${i}-${item.task.slice(0, 12)}`}
                  className="rounded-xl border border-border bg-muted/40 px-3 py-2.5"
                >
                  <p className="text-xs font-semibold tracking-wide text-primary uppercase">
                    {item.assignee}
                  </p>
                  <p className="mt-1 leading-relaxed">{item.task}</p>
                </li>
              ))}
            </ul>
          ) : (
            <EmptyNote>No action items were identified.</EmptyNote>
          )}
        </InsightCard>

        <InsightCard
          title="Decisions"
          icon={<Gavel className="size-4" />}
          copyValue={insights.decisions.join("\n")}
        >
          {insights.decisions.length ? (
            <ol className="space-y-2.5">
              {insights.decisions.map((decision, i) => (
                <li
                  key={`${i}-${decision.slice(0, 12)}`}
                  className="flex gap-3 rounded-xl bg-muted/50 px-3 py-2.5 leading-relaxed"
                >
                  <span className="flex size-5 shrink-0 items-center justify-center rounded-md bg-primary/15 text-xs font-semibold text-primary">
                    {i + 1}
                  </span>
                  <span>{decision}</span>
                </li>
              ))}
            </ol>
          ) : (
            <EmptyNote>No decisions were identified.</EmptyNote>
          )}
        </InsightCard>

        <InsightCard
          title="Topics Discussed"
          icon={<Tags className="size-4" />}
          copyValue={insights.topics.join("\n")}
        >
          {insights.topics.length ? (
            <ul className="flex flex-wrap gap-2">
              {insights.topics.map((topic, i) => (
                <li
                  key={`${i}-${topic.slice(0, 12)}`}
                  className="rounded-full border border-primary/30 bg-primary/10 px-3 py-1.5 text-xs font-medium text-primary"
                >
                  {topic}
                </li>
              ))}
            </ul>
          ) : (
            <EmptyNote>No topics were identified.</EmptyNote>
          )}
        </InsightCard>
      </div>
    </div>
  );
}
